import polars as pl
from helpers.argparse import get_args
from sklearn.model_selection import train_test_split
from helpers.eda import get_column_value_frequency
import duckdb

args = get_args()
data_directory = "project/data/energy"
filename = "energy.parquet"
df = pl.read_parquet(f"{data_directory}/s_{filename}")

if args.verbose:
    print("\nSILVER DATA STRUCTURE ---")
    df.glimpse()

unique_ids = df.select("ID").unique()
print(f"Number of unique IDs: {len(unique_ids)}")

print("\nBEGINNING DATA PROCESSING ---")
# Do some mutations for modeling, remove junk data, and prepare for splitting
df = duckdb.sql(
    """
    SELECT
        ID
        , BuildingName
        , EUI_WN AS EuiWN
        , Year
        , Years
        , NumYears
        , Year - YearBuilt AS BuildingAge
        , PropertyGFABuildings AS TotalBuildingFloorSpace
        , CASE WHEN NumberofFloors > 1 THEN 1 ELSE 0 END AS HasMultipleFloors
        , CASE WHEN NumberofBuildings > 1 THEN 1 ELSE 0 END AS HasMultipleBuildings
        , CASE
            WHEN BuildingType LIKE 'Multifamily%' THEN 'MultiFamily'
            ELSE BuildingType
        END AS BuildingType
    FROM df
    -- Below filters remove some suspected junk rows
    WHERE NumberofFloors > 0
    AND NumberofBuildings > 0
    AND PropertyGFABuildings < 10000000 -- Remove a single problematic outlier
    """
).pl()

print("\nPREPARING IDS FOR SPLITS ---")
eligible_ids = duckdb.sql(
    """
    SELECT
        ID
        , BuildingType
    FROM df
    WHERE Year == 2025
    AND NumYears > 1
    """
).pl()

ids_2025_only = duckdb.sql(
    """
    SELECT ID
    FROM df
    WHERE Year == 2025
    AND NumYears == 1
    """
).pl()

modeling_ids, holdout_ids = train_test_split(eligible_ids.select("ID"), test_size=0.2, random_state=100, stratify=eligible_ids.select("BuildingType"))

holdout_ids = pl.concat([holdout_ids, ids_2025_only])

print("\nPROCESSING SPLITS ---")
# Can't do a semi join on modeling ids as it doesnt contain all IDs we can use for training
# Such as those w/ no 2025 data
# So we just have to ensure we aren't using any IDs from the holdout set
train_full = duckdb.sql(
    """
    SELECT 
        df.*
        EXCLUDE(df.Years, df.NumYears)
    FROM df
    ANTI JOIN holdout_ids USING(ID)
    WHERE Year < 2025
    """
).pl()

train_deduplicated = duckdb.sql(
    """
    WITH randomized_index AS (
        SELECT
            *
            , RANDOM() AS rand
        FROM train_full
    )
    SELECT
        *
        EXCLUDE(rand)
    FROM randomized_index
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY ID
        ORDER BY rand
    ) = 1
    """
).pl()

test = duckdb.sql(
    """
    SELECT 
        df.*
        EXCLUDE(df.Years, df.NumYears)
    FROM df
    SEMI JOIN modeling_ids USING(ID)
    WHERE Year = 2025
    """
).pl()

holdout = duckdb.sql(
    """
    SELECT 
        df.*
        EXCLUDE(df.Years, df.NumYears)
    FROM df
    SEMI JOIN holdout_ids USING(ID)
    WHERE Year = 2025
    """
).pl()

print("\nSPLITS PROCESSED ---")
if args.verbose:
    print("\nSHOWING ALL DATASETS ---")
    print("Full training set")
    train_full.glimpse()
    print("Deduplicated training set")
    train_deduplicated.glimpse()
    print("Testing set")
    test.glimpse()
    print("Holdout set")
    holdout.glimpse()

for name, data in {
    "train_full": train_full,
    "train_deduplicated": train_deduplicated,
    "test": test,
    "holdout": holdout
}.items():
    print(f"{name}: {data.shape}")

print("\nRUNNING VALIDATION TESTS ---")
# Generated by chatgpt
# Deduplicated train set should contain one row per id
assert train_deduplicated["ID"].n_unique() == train_deduplicated.height

# Train full should contain no ids from holdout
assert train_full.join(
    holdout, on="ID", how="inner"
).is_empty()

# Test should contain no ids from holdout
assert test.join(
    holdout, on="ID", how="inner"
).is_empty()

# Test and holdout should only have 2025 entries
assert test["Year"].unique().to_list() == [2025]
assert holdout["Year"].unique().to_list() == [2025]

if args.write:
    print(f"\nWRITING DATASETS TO {data_directory} ---")
    train_full.write_parquet(f"{data_directory}/train_full.parquet")
    train_deduplicated.write_parquet(f"{data_directory}/train_deduplicated.parquet")
    test.write_parquet(f"{data_directory}/test.parquet")
    holdout.write_parquet(f"{data_directory}/holdout.parquet")
    print("All files written.")
else:
    print("Skipping write step")